// Create a double-clickable HTML copy from the readable, separate source files.
// No third-party bundler: this project only uses relative, named ES module imports.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = new Map();
const visiting = new Set();

async function bundleModule(path) {
  const key = relative(root, path).replaceAll('\\', '/');
  if (modules.has(key)) return key;
  if (visiting.has(key)) throw new Error(`Circular import: ${key}`);
  visiting.add(key);
  let source = await readFile(path, 'utf8');
  const imports = [...source.matchAll(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];\s*$/gm)];

  for (const [statement, names, dependency] of imports) {
    if (!dependency.startsWith('.')) throw new Error(`Only local modules are supported: ${dependency}`);
    const dependencyKey = await bundleModule(resolve(dirname(path), dependency));
    const bindings = names.split(',').map(name => name.trim().replace(/\s+as\s+/, ': ')).join(', ');
    source = source.replace(statement, `const { ${bindings} } = __modules[${JSON.stringify(dependencyKey)}];\n`);
  }

  const exports = [...source.matchAll(/^export\s+(?:const|let|function|class)\s+(\w+)/gm)].map(match => match[1]);
  source = source.replace(/^export\s+/gm, '');
  if (/^\s*(import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax in ${key}`);
  modules.set(key, `// Source: ${key}\n__modules[${JSON.stringify(key)}] = (() => {\n${source}\nreturn { ${exports.join(', ')} };\n})();`);
  visiting.delete(key);
  return key;
}

await bundleModule(resolve(root, 'js/app.js'));
let html = await readFile(resolve(root, 'index.html'), 'utf8');
for (const [tag, stylesheet] of html.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)) {
  const css = await readFile(resolve(root, stylesheet), 'utf8');
  html = html.replace(tag, `<style>\n/* Source: ${stylesheet} */\n${css}</style>`);
}
html = html.replace(/\s*<script type="module" src="js\/app\.js"><\/script>/, '');
const script = `(function () {\n'use strict';\nconst __modules = Object.create(null);\n\n${[...modules.values()].join('\n\n')}\n})();`;
html = html.replace('</body>', `<!-- Generated by npm run bundle. Edit the separate source files to make changes. -->\n<script>\n${script.replace(/<\/script/gi, '<\\/script')}\n</script>\n</body>`);
const output = resolve(root, 'Cricket-Scoreboard.html');
await writeFile(output, html);
console.log(`Created ${output}. Open this file directly in a browser; no server needed.`);
